#!/usr/bin/env python3
"""Inventory the raw lesson archives under sources/ (hash, chapter, subchapter, phase, duplicates).

Writes sources/inventory.json and docs/SOURCE-INVENTORY.md. Never modifies the archives.
"""
from __future__ import annotations
import hashlib, html, json, re, sys, zipfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'sources'
AREAS = ['archive-md', 'archive-docx', 'legacy-sites']
FA_DIGITS = str.maketrans('۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789')


def norm(s: str) -> str:
    return s.translate(FA_DIGITS).replace('‌', '')


def text_digest(p: Path, data: bytes) -> str:
    """Hash of normalized text, so re-saved Word copies of the same text are detected."""
    if p.suffix.lower() == '.docx':
        try:
            xml = zipfile.ZipFile(p).read('word/document.xml').decode('utf8')
        except Exception:
            return ''
        text = html.unescape(re.sub(r'<[^>]+>', ' ', xml.replace('</w:p>', '\n')))
    else:
        text = data.decode('utf8', 'replace')
    text = re.sub(r'\s+', ' ', text).strip()
    return hashlib.sha256(text.encode('utf8')).hexdigest()


def classify(rel: str) -> dict:
    n = norm(rel)
    info = {'chapter': None, 'subchapter': None, 'phase': 'other', 'unit': None}
    m = re.search(r'فصل_?(\d{1,2})_?زیرفصل_(\d+)-(\d+)', n) or re.search(r'زیرفصل_(\d+)-(\d+)', n)
    if m:
        g = m.groups()
        ch, sub = (g[1], g[2]) if len(g) == 3 else g
        info['chapter'] = f'{int(ch):02}'
        info['subchapter'] = f'{int(ch):02}-{int(sub):02}'
    else:
        m = re.search(r'فصل_?(\d{1,2})', n)
        if m:
            info['chapter'] = f'{int(m.group(1)):02}'
    if 'جامع_نهایی' in n:
        info['phase'] = 'final'
    elif re.search(r'فاز(\d)', n):
        info['phase'] = 'phase' + re.search(r'فاز(\d)', n).group(1)
    elif 'طرح_درسنامه' in n:
        info['phase'] = 'outline'
    elif re.search(r'/(\d\d)_[a-zA-Z0-9_]+/lesson\.md$', n):
        info['phase'] = 'legacy-unit-lesson'
    elif re.search(r'/(\d\d)_[a-zA-Z0-9_]+/questions\.json$', n):
        info['phase'] = 'legacy-unit-questions'
    elif 'legacy-sites/' in rel and rel.endswith('index.html'):
        info['phase'] = 'legacy-site'
    elif 'راهنمای' in n:
        info['phase'] = 'guide'
    elif 'پرامپت' in n:
        info['phase'] = 'prompt-architecture'
    u = re.search(r'/(\d\d)_([a-zA-Z0-9_]+)/(lesson\.md|questions\.json)$', n)
    if u:
        info['unit'] = f'{u.group(1)}_{u.group(2)}'
    if 'legacy-sites/ravanhamych1' in rel:
        info.update(chapter='01', subchapter='01-02')
    if 'legacy-sites/ravanhamych2' in rel:
        info.update(chapter='02')
    return info


def main() -> int:
    records = []
    for area in AREAS:
        base = SRC / area
        if not base.exists():
            continue
        for p in sorted(base.rglob('*')):
            if not p.is_file() or p.name == 'SNAPSHOT.txt':
                continue
            rel = p.relative_to(SRC).as_posix()
            data = p.read_bytes()
            rec = {'path': rel, 'area': area, 'bytes': len(data),
                   'sha256': hashlib.sha256(data).hexdigest(),
                   'text_sha256': text_digest(p, data),
                   'format': p.suffix.lstrip('.').lower(),
                   'misleading_name': p.name.endswith('.md.docx') or bool(re.search(r'\(\d\)\.docx$', p.name))}
            rec.update(classify(rel))
            records.append(rec)
    by_hash = defaultdict(list)
    for r in records:
        by_hash[r['sha256']].append(r['path'])
    by_text = defaultdict(list)
    for r in records:
        if r['text_sha256']:
            by_text[r['text_sha256']].append(r['path'])
    for r in records:
        r['identical_to'] = [x for x in by_hash[r['sha256']] if x != r['path']]
        r['same_text_as'] = [x for x in by_text.get(r['text_sha256'], []) if x != r['path'] and x not in r['identical_to']]
    (SRC / 'inventory.json').write_text(json.dumps(records, ensure_ascii=False, indent=1) + '\n', encoding='utf8')

    subs = defaultdict(lambda: defaultdict(list))
    for r in records:
        if r['subchapter']:
            subs[r['subchapter']][r['area']].append(r)
    lines = ['# Source inventory (generated)', '',
             'Generated by `python3 scripts/inventory_sources.py`. Do not edit by hand.',
             'A file name ending in `.md.docx` is a Word document, not Markdown. "final" in a name is not scientific approval.', '',
             f'Total files: **{len(records)}** · byte-identical groups: **{sum(1 for v in by_hash.values() if len(v) > 1)}**', '',
             '| Subchapter | archive-md | archive-docx | phases (docx) | docx with a same-text twin |',
             '| --- | ---: | ---: | --- | ---: |']
    for sid in sorted(subs):
        md = subs[sid].get('archive-md', []) + subs[sid].get('legacy-sites', [])
        dx = subs[sid].get('archive-docx', [])
        phases = ', '.join(sorted({r['phase'] for r in dx})) or '—'
        dup = sum(1 for r in dx if any(x.startswith('archive-docx') for x in r['identical_to'] + r['same_text_as']))
        lines.append(f'| {sid} | {len(md)} | {len(dx)} | {phases} | {dup} |')
    lines += ['', '## Files without a subchapter', '']
    lines += [f'- `{r["path"]}` ({r["phase"]})' for r in records if not r['subchapter']]
    (ROOT / 'docs' / 'SOURCE-INVENTORY.md').write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(f'Inventoried {len(records)} files across {len(subs)} subchapters')
    return 0


if __name__ == '__main__':
    sys.exit(main())
